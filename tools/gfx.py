# --------------------------------------------------------- window border (2px)
def rect_tile(hlines, vlines):
    pix = [[0]*8 for _ in range(8)]
    for y in hlines:
        for x in range(8): pix[y][x] = 3
    for x in vlines:
        for y in range(8): pix[y][x] = 3
    return pix

def punch(pix, xs, ys, val=0):
    for y in ys:
        for x in xs: pix[y][x] = val
    return pix

BORD_T  = BG.add(rect_tile([1, 2], []))
