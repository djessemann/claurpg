# window border tiles (2px inset frame)
def corner(top, left):
    p = [[0]*8 for _ in range(8)]
    ys = (1,2) if top else (5,6)
    xs = (1,2) if left else (5,6)
    for y in ys:
        for x in (range(xs[0],8) if left else range(0,xs[1]+1)): p[y][x]=3
    for x in xs:
        for y in (range(ys[0],8) if top else range(0,ys[1]+1)): p[y][x]=3
    return p
def edge(h,v):
    p=[[0]*8 for _ in range(8)]
    for y in h:
        for x in range(8): p[y][x]=3
    for x in v:
        for y in range(8): p[y][x]=3
    return p
