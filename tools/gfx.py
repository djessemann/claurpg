# --------------------------------------------------------------- tile bank
class Bank:
    def __init__(self, dedup=True):
        self.tiles = [bytes(16)]
        self.lookup = {bytes(16): 0}
        self.dedup = dedup

    def add(self, pix):
        lo = bytearray(8); hi = bytearray(8)
        for y, row in enumerate(pix):
            for x, c in enumerate(row):
                if c & 1: lo[y] |= 0x80 >> x
                if c & 2: hi[y] |= 0x80 >> x
        key = bytes(lo + hi)
        if self.dedup and key in self.lookup:
            return self.lookup[key]
        idx = len(self.tiles)
        if idx > 255:
            raise SystemExit("bank overflow")
        self.tiles.append(key)
        self.lookup[key] = idx
        return idx

    def data(self):
        out = b"".join(self.tiles)
        return out + bytes(4096 - len(out))

BG = Bank()
SPR = Bank(dedup=False)

MAP = {".": 0, "0": 0, "1": 1, "2": 2, "3": 3}

def parse(art, m=MAP):
    rows = art.strip("\n").split("\n")
    w = max(len(r) for r in rows)
    w = (w + 7) & ~7
    rows = [r.ljust(w, ".")[:w] for r in rows]
    return [[m[c] for c in row] for row in rows]

def grid(bank, art, scale=1, m=MAP):
    pix = parse(art, m)
    if scale > 1:
        pix = [[c for c in row for _ in range(scale)] for row in pix for _ in range(scale)]
    h = len(pix); w = len(pix[0])
    assert w % 8 == 0 and h % 8 == 0, f"{w}x{h}"
    tw, th = w // 8, h // 8
    ids = []
    for ty in range(th):
        for tx in range(tw):
            ids.append(bank.add([pix[ty*8+y][tx*8:tx*8+8] for y in range(8)]))
    return tw, th, ids

