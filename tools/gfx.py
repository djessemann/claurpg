with open(os.path.join(ROOT, "src", "gen", "tileids.inc"), "w") as f:
    f.write("; generated by tools/gfx.py — do not edit\n")
    for ch in FONT_ORDER:
        name = ch
        if ch.isalnum():
            name = "CH_" + ch
        else:
            name = "CH_" + {".": "DOT", ",": "COMMA", "!": "BANG", "?": "QMARK",
                            "'": "APOS", "-": "DASH", ":": "COLON", ">": "CURSOR",
                            "/": "SLASH"}[ch]
        f.write(f"{name} = ${font_ids[ch]:02X}\n")
    for nm, val in [("BORD_T", BORD_T), ("BORD_B", BORD_B), ("BORD_L", BORD_L),
                    ("BORD_R", BORD_R), ("BORD_TL", BORD_TL), ("BORD_TR", BORD_TR),
                    ("BORD_BL", BORD_BL), ("BORD_BR", BORD_BR)]:
        f.write(f"{nm} = ${val:02X}\n")
    for i, (name, pal, flags, ids) in enumerate(METATILES):
        f.write(f"MT_{name} = {i}\n")
    f.write(f"NUM_METATILES = {len(METATILES)}\n")
    for name, ids in SPRITES.items():
        f.write(f"SPR_{name} = ${ids[0]:02X}\n")
    for name, (tw, th, ids) in ENEMIES.items():
        f.write(f"{name}_W = {tw}\n{name}_H = {th}\n")

with open(os.path.join(ROOT, "src", "gen", "gfxdata.s"), "w") as f:
    f.write('; generated by tools/gfx.py — do not edit\n.include "gen/tileids.inc"\n')
    f.write(".segment \"RODATA\"\n")
    for part in range(4):
        f.write(f".export _mt_{'tl tr bl br'.split()[part]}\n")
        f.write(f"_mt_{'tl tr bl br'.split()[part]}:\n")
        for name, pal, flags, ids in METATILES:
            f.write(f"  .byte ${ids[part]:02X} ; {name}\n")
    f.write(".export _mt_attr\n_mt_attr:\n")
    for name, pal, flags, ids in METATILES:
        f.write(f"  .byte ${pal | flags:02X} ; {name}\n")
    for name, (tw, th, ids) in ENEMIES.items():
        f.write(f".export _{name}\n_{name}:\n")
        for r in range(th):
            row = ids[r*tw:(r+1)*tw]
            f.write("  .byte " + ",".join(f"${t:02X}" for t in row) + "\n")

# sprite metasprite check: sprite tiles must be consecutive TL,TR,BL,BR
for name, ids in SPRITES.items():
    base = ids[0]
    assert ids == [base, base+1, base+2, base+3], f"sprite {name} not consecutive: {ids}"

