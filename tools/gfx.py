# ---------------------------------------------------------------- tile store
class Bank:
    def __init__(self, dedup=True):
        self.tiles = [bytes(16)]          # tile 0 = blank
        self.lookup = {bytes(16): 0}
        self.dedup = dedup

    def add(self, pix):
        """pix: list of 8 rows of 8 ints (0-3). Returns tile index (deduped)."""
        lo = bytearray(8); hi = bytearray(8)
        for y, row in enumerate(pix):
            for x, c in enumerate(row):
                if c & 1: lo[y] |= 0x80 >> x
                if c & 2: hi[y] |= 0x80 >> x
        key = bytes(lo + hi)
        if self.dedup and key in self.lookup:
            return self.lookup[key]
        idx = len(self.tiles)
        if idx > 255:
            raise SystemExit("bank overflow (>256 tiles)")
        self.tiles.append(key)
        self.lookup[key] = idx
        return idx

    def data(self):
        out = b"".join(self.tiles)
        return out + bytes(4096 - len(out))

BG = Bank()
SPR = Bank(dedup=False)

def parse(art, mapping):
    rows = [r for r in art.strip("\n").split("\n")]
    w = max(len(r) for r in rows)
    if w % 8:
        w += 8 - w % 8
    rows = [r.ljust(w, ".")[:w] for r in rows]
    return [[mapping[ch] for ch in row] for row in rows]

def grid_tiles(bank, art, mapping, scale=1):
    """Split a WxH pixel art into 8x8 tiles (row-major). Returns (tw, th, ids)."""
    pix = parse(art, mapping)
    if scale > 1:
        pix = [[c for c in row for _ in range(scale)] for row in pix for _ in range(scale)]
    h = len(pix); w = len(pix[0])
    for row in pix:
        assert len(row) == w, "ragged art"
    assert w % 8 == 0 and h % 8 == 0, f"art not tile aligned {w}x{h}"
    tw, th = w // 8, h // 8
    ids = []
    for ty in range(th):
        for tx in range(tw):
            tile = [pix[ty*8+y][tx*8:tx*8+8] for y in range(8)]
            ids.append(bank.add(tile))
    return tw, th, ids

