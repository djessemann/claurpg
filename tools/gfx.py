BORD_L  = BG.add(rect_tile([], [1, 2]))
BORD_R  = BG.add(rect_tile([], [5, 6]))
def corner(top, left):
    pix = [[0]*8 for _ in range(8)]
    ys = (1, 2) if top else (5, 6)
    xs = (1, 2) if left else (5, 6)
    x0, x1 = (xs[0], 8) if left else (0, xs[1]+1)
    y0, y1 = (ys[0], 8) if top else (0, ys[1]+1)
    for y in ys:
        for x in range(x0, x1): pix[y][x] = 3
    for x in xs:
        for y in range(y0, y1): pix[y][x] = 3
    return pix
BORD_TL = BG.add(corner(True, True))
BORD_TR = BG.add(corner(True, False))
BORD_BL = BG.add(corner(False, True))
BORD_BR = BG.add(corner(False, False))

