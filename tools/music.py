#!/usr/bin/env python3
"""EMBERFALL — music compiler.

Songs are written as (note, beats) tuples per channel; emits src/gen/songs.s
with the NTSC period table and event streams for the driver in sound.s.
Stream format: [note-index, frames] pairs; 'r' = rest ($FF), loop with $FE.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# note index 0 = A1 (55 Hz), chromatic upward
NAMES = ["a", "a+", "b", "c", "c+", "d", "d+", "e", "f", "f+", "g", "g+"]
N_NOTES = 60

def idx(note):
    """'c4' -> semitones above A1. octave numbering: c4..b4 contains a4."""
    name = note[:-1]
    octv = int(note[-1])
    s = NAMES.index(name)
    # a,a+,b belong to octave o at index (o-1)*12 + s; c..g+ at (o-2)*12 + s
    if s < 3:
        return (octv - 1) * 12 + s
    return (octv - 2) * 12 + s

def period(i):
    f = 55.0 * (2.0 ** (i / 12.0))
    return round(1789773 / (16 * f)) - 1

def stream(events, beat_frames):
    out = []
    for note, beats in events:
        dur = round(beats * beat_frames)
        while dur > 0:
            d = min(dur, 255)
            out.append(0xFF if note == "r" else idx(note))
            out.append(d)
            dur -= d
    out.append(0xFE)
    return out

Q = 1        # quarter
H = 2
W = 4
E = 0.5

# --------------------------------------------------------------------- songs
