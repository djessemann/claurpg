os.makedirs(os.path.join(ROOT, "src", "gen"), exist_ok=True)
with open(os.path.join(ROOT, "src", "gen", "songs.s"), "w") as f:
    f.write("; generated by tools/music.py — do not edit\n")
    f.write('.segment "RODATA"\n')
    f.write("note_lo:\n")
    for i in range(N_NOTES):
        f.write(f"  .byte <{period(i)}\n")
    f.write("note_hi:\n")
    for i in range(N_NOTES):
        f.write(f"  .byte >{period(i)}\n")
    for name, mel, bas, bf in SONGS:
        for ch, ev in (("m", mel), ("b", bas)):
            data = stream(ev, bf)
            f.write(f"song_{name}_{ch}:\n")
            for k in range(0, len(data), 16):
                f.write("  .byte " + ",".join(f"${b:02X}" for b in data[k:k+16]) + "\n")
    f.write("song_tbl:\n")
    for name, _, _, _ in SONGS:
        f.write(f"  .word song_{name}_m, song_{name}_b\n")

for i in (0, 12, 24, 36, 48):
    assert period(i) < 2048
print("songs.s emitted")
